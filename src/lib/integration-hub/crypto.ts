/**
 * Integration Hub credential-vault encryption (P7 Stage B).
 *
 * The Hub vault is the FIRST place in this app where an operator can
 * store a credential value and later reveal it again — so values are
 * encrypted at rest with AES-256-GCM under a DEDICATED key,
 * `INTEGRATION_HUB_ENCRYPTION_KEY` (server-only, base64, exactly
 * 32 bytes). The key is deliberately separate from the OAuth mailbox
 * key (`TOKEN_ENCRYPTION_KEY`, src/lib/oauth/crypto.ts): the two
 * vaults have different blast radii and fail independently.
 *
 * Wire format (identical construction to the OAuth vault):
 *
 *     v1.<iv>.<tag>.<ciphertext>
 *
 * where each segment is base64url: 12-byte random IV, the GCM auth
 * tag, and the ciphertext. Decryption fails closed on ANY anomaly —
 * wrong key, tampered segment, malformed format, unsupported version.
 * Losing the key makes stored Hub credentials undecryptable BY DESIGN:
 * they must be re-entered. There is no recovery path and no dual-key
 * decrypt in v1.
 *
 * Fail-closed discipline:
 *   - `isHubVaultConfigured()` never throws (safe for status reads).
 *   - `encryptHubSecret` / `decryptHubSecret` throw `HubVaultError`
 *     with messages that explain the OPERATOR fix; they never include
 *     the plaintext or any ciphertext fragment.
 */
import {
  createCipheriv,
  createDecipheriv,
  randomBytes,
} from "node:crypto";

export const HUB_VAULT_KEY_ENV = "INTEGRATION_HUB_ENCRYPTION_KEY";

const FORMAT_VERSION = "v1";
const ALGORITHM = "aes-256-gcm";
const IV_BYTES = 12;
const KEY_BYTES = 32;

/**
 * Minimal env shape for the vault key. Lets tests inject a key without
 * touching `process.env`.
 */
export interface HubVaultEnv {
  INTEGRATION_HUB_ENCRYPTION_KEY?: string | undefined;
}

function envFromProcess(): HubVaultEnv {
  return {
    INTEGRATION_HUB_ENCRYPTION_KEY:
      process.env.INTEGRATION_HUB_ENCRYPTION_KEY,
  };
}

export class HubVaultError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "HubVaultError";
  }
}

function looksLikePlaceholder(value: string): boolean {
  const v = value.trim().toLowerCase();
  return (
    v.startsWith("change-me") ||
    v.startsWith("your-") ||
    v.startsWith("your_") ||
    v.includes("placeholder")
  );
}

/**
 * Resolve and strictly validate the vault key from the env. Throws
 * `HubVaultError` when the key is missing, a placeholder, or not
 * base64 for exactly 32 bytes.
 */
export function getHubEncryptionKey(env: HubVaultEnv = envFromProcess()): Buffer {
  const raw = (env[HUB_VAULT_KEY_ENV] ?? "").trim();
  if (!raw) {
    throw new HubVaultError(
      `${HUB_VAULT_KEY_ENV} is not set. The Integration Hub credential ` +
        `vault cannot encrypt or decrypt without it. Generate one with ` +
        `\`openssl rand -base64 32\` and set it in the deployment ` +
        `environment (see SETUP.md, Integration Hub section).`
    );
  }
  if (looksLikePlaceholder(raw)) {
    throw new HubVaultError(
      `${HUB_VAULT_KEY_ENV} is still a placeholder value. Replace it ` +
        `with a real key generated by \`openssl rand -base64 32\` ` +
        `before storing Hub credentials.`
    );
  }
  let key: Buffer;
  try {
    key = Buffer.from(raw, "base64");
  } catch {
    throw new HubVaultError(
      `${HUB_VAULT_KEY_ENV} is not valid base64. Expected the output ` +
        `of \`openssl rand -base64 32\`.`
    );
  }
  if (key.length !== KEY_BYTES) {
    throw new HubVaultError(
      `${HUB_VAULT_KEY_ENV} must decode to exactly ${KEY_BYTES} bytes ` +
        `(got ${key.length}). Generate one with ` +
        `\`openssl rand -base64 32\`.`
    );
  }
  return key;
}

/**
 * Non-throwing configuration check (status surfaces, route guards that
 * must answer 503 rather than crash).
 */
export function isHubVaultConfigured(env: HubVaultEnv = envFromProcess()): boolean {
  try {
    getHubEncryptionKey(env);
    return true;
  } catch {
    return false;
  }
}

function toB64Url(buf: Buffer): string {
  return buf.toString("base64url");
}

function fromB64Url(segment: string): Buffer {
  return Buffer.from(segment, "base64url");
}

/**
 * Encrypt a credential value for storage in `hub_credentials.value_enc`.
 * Returns the `v1.<iv>.<tag>.<ct>` envelope string.
 */
export function encryptHubSecret(
  plaintext: string,
  env: HubVaultEnv = envFromProcess()
): string {
  if (typeof plaintext !== "string" || plaintext.length === 0) {
    throw new HubVaultError("Refusing to encrypt an empty credential value.");
  }
  const key = getHubEncryptionKey(env);
  const iv = randomBytes(IV_BYTES);
  const cipher = createCipheriv(ALGORITHM, key, iv);
  const ciphertext = Buffer.concat([
    cipher.update(plaintext, "utf8"),
    cipher.final(),
  ]);
  const tag = cipher.getAuthTag();
  return [FORMAT_VERSION, toB64Url(iv), toB64Url(tag), toB64Url(ciphertext)].join(
    "."
  );
}

/**
 * Decrypt a stored `value_enc` envelope. Throws `HubVaultError` on any
 * problem (format, version, key, tamper). The returned plaintext must
 * only ever leave the server in a strict-audited reveal/copy response
 * or an explicitly-requested export — never in a list, log, audit row,
 * or error message.
 */
export function decryptHubSecret(
  envelope: string,
  env: HubVaultEnv = envFromProcess()
): string {
  if (typeof envelope !== "string" || envelope.length === 0) {
    throw new HubVaultError(
      "Stored Hub credential is empty or missing — it cannot be decrypted. " +
        "The credential must be re-entered."
    );
  }
  const parts = envelope.split(".");
  if (parts.length !== 4) {
    throw new HubVaultError(
      "Stored Hub credential has an unrecognised format — it cannot be " +
        "decrypted. The credential must be re-entered."
    );
  }
  const [version, ivSeg, tagSeg, ctSeg] = parts;
  if (version !== FORMAT_VERSION) {
    throw new HubVaultError(
      `Stored Hub credential uses unsupported format version "${version}". ` +
        "The credential must be re-entered."
    );
  }
  const key = getHubEncryptionKey(env);
  try {
    const decipher = createDecipheriv(ALGORITHM, key, fromB64Url(ivSeg));
    decipher.setAuthTag(fromB64Url(tagSeg));
    const plaintext = Buffer.concat([
      decipher.update(fromB64Url(ctSeg)),
      decipher.final(),
    ]);
    return plaintext.toString("utf8");
  } catch {
    throw new HubVaultError(
      "Stored Hub credential could not be decrypted (wrong key or " +
        "corrupted value). If INTEGRATION_HUB_ENCRYPTION_KEY was rotated " +
        "or lost, stored Hub credentials cannot be recovered — they must " +
        "be re-entered."
    );
  }
}

/**
 * The only fragment of a value that may be shown outside a disclosure:
 * the last 4 characters (fewer for very short values). Computed at
 * write time and stored as `value_last4`.
 */
export function hubSecretLast4(plaintext: string): string {
  return plaintext.slice(-4);
}
