// Node parameters for the NxtSend action node.
//
// Programmatic-style node (see NxtSend.node.ts for why): several operations
// need more than one API call (Analytics "Compare Campaigns", "Get Lead
// Statistics"), and the trigger needs polling dedupe + webhook lifecycle
// logic that declarative routing cannot express.
//
// Every operation maps to exactly one endpoint in
// `../shared/constants.ts` (OPERATION_ENDPOINTS); the tests assert the
// description and the map agree.
